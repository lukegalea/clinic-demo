defmodule Atlas.Tokens do
  @moduledoc """
  The Atlas design tokens as data, and the CSS generated from them.

  `priv/atlas/tokens.json` holds the tokens in the W3C Design Tokens format,
  transcribed from the Atlas Figma library. `priv/atlas/bridge.json` says
  which existing custom property (A2UI's, the admin catalog's, the current
  theme's) takes which token. `css/2` turns the two into one stylesheet, so no
  colour, size or shadow is ever typed anywhere else.

  Every token becomes a runtime custom property (`--atlas-bg-brand`), because
  A2UI components render in shadow DOM and custom properties are the only
  thing that crosses that boundary.
  """

  @tokens_path "priv/atlas/tokens.json"
  @bridge_path "priv/atlas/bridge.json"

  @doc "Reads and flattens the token file: `%{\"bg.brand\" => \"#0B62DF\", ...}`, aliases resolved."
  def load(path \\ @tokens_path) do
    path |> File.read!() |> Jason.decode!() |> flatten()
  end

  @doc "Reads the bridge file: `%{group => %{target_property => value}}`."
  def load_bridge(path \\ @bridge_path) do
    path
    |> File.read!()
    |> Jason.decode!()
    |> Map.reject(fn {key, _} -> String.starts_with?(key, "$") end)
  end

  @doc """
  Flattens a decoded token tree into dotted paths and resolves `{a.b.c}`
  aliases. Raises on an alias that names no token, so a typo fails the build.
  """
  def flatten(tree) do
    raw = collect(tree, [], %{})
    Map.new(raw, fn {path, value} -> {path, resolve(value, raw, [path])} end)
  end

  @doc "The custom-property name for a token path: `bg.brand` → `--atlas-bg-brand`."
  def property(path), do: "--atlas-" <> String.replace(path, ".", "-")

  @doc "The generated stylesheet."
  def css(tokens \\ load(), bridge \\ load_bridge()) do
    [
      header(),
      font_face(),
      block(":root", Enum.sort(tokens), fn {path, value} -> {property(path), css_value(value)} end),
      Enum.map(Enum.sort(bridge), fn {group, entries} ->
        entries = Map.reject(entries, fn {key, _} -> String.starts_with?(key, "$") end)

        [
          "\n/* bridge: ",
          group,
          " */\n",
          block(selector(group), Enum.sort(entries), fn {target, value} ->
            {target, bridge_value(value, tokens, target)}
          end)
        ]
      end)
    ]
    |> IO.iodata_to_binary()
  end

  # The `tailwind` group overrides Tailwind's own theme values; every other
  # group overrides runtime custom properties on :root.
  defp selector("tailwind"), do: "@theme"
  defp selector(_group), do: ":root"

  defp collect(%{"$value" => value}, path, acc), do: Map.put(acc, Enum.join(path, "."), value)

  defp collect(map, path, acc) when is_map(map) do
    Enum.reduce(map, acc, fn
      {"$" <> _, _}, acc -> acc
      {key, child}, acc -> collect(child, path ++ [key], acc)
    end)
  end

  defp collect(_other, _path, acc), do: acc

  defp resolve("{" <> rest, raw, seen) do
    target = String.trim_trailing(rest, "}")

    cond do
      target in seen ->
        raise ArgumentError, "Atlas token alias cycle: #{Enum.join(seen, " → ")}"

      not Map.has_key?(raw, target) ->
        raise ArgumentError, "Atlas token #{hd(seen)} aliases unknown token {#{target}}"

      true ->
        resolve(Map.fetch!(raw, target), raw, [target | seen])
    end
  end

  defp resolve(value, _raw, _seen), do: value

  defp bridge_value("{" <> rest, tokens, target) do
    path = String.trim_trailing(rest, "}")

    unless Map.has_key?(tokens, path),
      do: raise(ArgumentError, "bridge entry #{target} names unknown Atlas token {#{path}}")

    "var(#{property(path)})"
  end

  defp bridge_value(literal, _tokens, _target) when is_binary(literal), do: literal

  defp css_value(list) when is_list(list), do: Enum.map_join(list, ", ", &family/1)
  defp css_value(value), do: to_string(value)

  defp family(name) do
    if String.contains?(name, " ") or name =~ ~r/^[A-Z]/, do: ~s("#{name}"), else: name
  end

  defp block(selector, entries, fun) do
    lines =
      Enum.map(entries, fn entry ->
        {k, v} = fun.(entry)
        ["  ", k, ": ", v, ";\n"]
      end)

    [selector, " {\n", lines, "}\n"]
  end

  defp header do
    """
    /* Generated by `mix atlas.tokens.build` from priv/atlas/tokens.json and
       priv/atlas/bridge.json. Do not edit: change the JSON and regenerate. */

    """
  end

  defp font_face do
    """
    @font-face {
      font-family: "Inter";
      font-style: normal;
      font-weight: 100 900;
      font-display: swap;
      src: url("/fonts/inter-latin.woff2") format("woff2");
      unicode-range: U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA,
        U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191,
        U+2193, U+2212, U+2215, U+FEFF, U+FFFD;
    }

    """
  end
end
